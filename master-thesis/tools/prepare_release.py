#!/usr/bin/env python3
"""Regenerate the scope-safe offline cache list after changing app assets/data."""
from pathlib import Path
import hashlib
import json

root=Path(__file__).resolve().parents[1]
files=['index.html','manifest.webmanifest','README.md']
files += [str(f.relative_to(root)) for folder in ['assets','data'] for f in sorted((root/folder).rglob('*')) if f.is_file()]
revision=hashlib.sha256(b''.join(str(f).encode()+(root/f).read_bytes() for f in files)).hexdigest()[:12]
pack={'revision':revision,'files':files,'scope':'Interface, full interactive datasets, reading edition, manuscript figures. Original research downloads are cached on access.'}
(root/'cache-manifest.json').write_text(json.dumps(pack,indent=2)+'\n')
sw="""// Generated by tools/prepare_release.py. Scoped to its folder, including GitHub project subpaths.
const PREFIX = 'forecast-atlas@' + new URL(self.registration.scope).pathname + '#';
const CACHE = PREFIX + '__REVISION__';
const SHELL = ['index.html','assets/app.js','assets/core.js','assets/charts.js','assets/style.css','assets/vendor/marked.js','assets/icon.svg','manifest.webmanifest'];
self.addEventListener('install', event => {event.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));});
self.addEventListener('activate', event => {event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith(PREFIX) && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));});
self.addEventListener('fetch', event => {
  const request=event.request,url=new URL(request.url);
  if(request.method!=='GET'||url.origin!==self.location.origin||!url.pathname.startsWith(new URL(self.registration.scope).pathname))return;
  event.respondWith(caches.open(CACHE).then(async cache => {
    const stored=await cache.match(request);
    if(stored && request.mode!=='navigate')return stored;
    try {const response=await fetch(request);if(response.ok && response.type==='basic')await cache.put(request,response.clone());return response;}
    catch(error){
      if(stored)return stored;
      const rootPath=new URL(self.registration.scope).pathname;
      if(request.mode==='navigate' && (url.pathname===rootPath || url.pathname===rootPath+'index.html')){
        const index=await cache.match(new URL('index.html',self.registration.scope));if(index)return index;
      }
      return new Response('This research file has not been saved for offline use. Reconnect to open the original artifact.',{status:503,headers:{'Content-Type':'text/plain'}});
    }
  }));
});
""".replace('__REVISION__',revision)
(root/'sw.js').write_text(sw)
print(f'Offline pack prepared: {len(files)} files, revision {revision}.')
